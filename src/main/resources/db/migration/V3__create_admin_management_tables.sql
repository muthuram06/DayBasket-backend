-- 1. VENDORS
CREATE TABLE vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(150),
    email VARCHAR(150),
    phone VARCHAR(20),
    address TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_vendors_active ON vendors(is_active);

-- 2. DELIVERY PARTNER CUSTOMER ASSIGNMENTS
-- One delivery partner can serve multiple customers.
-- A customer can be assigned to one delivery partner.

CREATE TABLE delivery_partner_customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_partner_user_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL UNIQUE,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_assignment_delivery_user
        FOREIGN KEY (delivery_partner_user_id)
        REFERENCES users(id),

    CONSTRAINT fk_assignment_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
);

CREATE INDEX idx_assignment_partner
ON delivery_partner_customers(delivery_partner_user_id);

-- 3. CUSTOMER ORDERS
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    delivery_partner_user_id BIGINT,
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'PLACED',
    delivery_address TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id),

    CONSTRAINT fk_orders_delivery_partner
        FOREIGN KEY (delivery_partner_user_id)
        REFERENCES users(id),

    CONSTRAINT chk_order_amount
        CHECK (total_amount >= 0),

    CONSTRAINT chk_order_status
        CHECK (status IN (
            'PLACED',
            'CONFIRMED',
            'PACKED',
            'OUT_FOR_DELIVERY',
            'DELIVERED',
            'CANCELLED'
        ))
);

CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_delivery_partner
ON orders(delivery_partner_user_id);

CREATE INDEX idx_orders_created
ON orders(created_at DESC);
